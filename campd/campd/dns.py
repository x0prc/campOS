"""Local DNS resolver with blocklists (defense-in-depth layer).

Per ADR-005 the primary control is the default-deny firewall; DNS blocking
ensures telemetry domains don't even resolve for flows the user has allowed.
Generates dnsmasq configuration — the ship-with default on Armbian.

Blocklist sources in ``DnsConfig.blocklists`` are either local files
(one domain per line, or hosts-format ``0.0.0.0 domain`` lines; ``#``
comments and blank lines ignored) or ``http(s)://`` URLs. URL sources are
fetched into a cache by an explicit ``campctl dns fetch`` (needs egress);
``apply`` — the boot path — only renders from cached/local content and
never touches the network, so the default-deny firewall can come up first.
"""

from __future__ import annotations

import hashlib
import ipaddress
import re
import tempfile
import urllib.request
from collections.abc import Callable
from pathlib import Path

from .config import DnsConfig

DNMASQ_CONF_PATH = Path("/etc/dnsmasq.d/campd.conf")
CACHE_DIR = Path("/var/cache/campd/blocklists")

# Size/time caps for list downloads (StevenBlack hosts is ~3 MB today).
FETCH_TIMEOUT_S = 60
FETCH_MAX_BYTES = 20 * 1024 * 1024

# Rough but safe: labels of alnum+hyphen, at least two labels, lowercase.
_DOMAIN_RE = re.compile(
    r"^(?!-)[a-z0-9-]{1,63}(?<!-)"
    r"(\.(?!-)[a-z0-9-]{1,63}(?<!-))+$"
)

GENERATED_HEADER = "# Generated by campd — do not edit (campctl dns apply)\n"


def is_url(source: str) -> bool:
    return source.startswith(("http://", "https://"))


def cache_path_for(url: str, cache_dir: Path = CACHE_DIR) -> Path:
    digest = hashlib.sha256(url.encode()).hexdigest()[:16]
    return cache_dir / f"{digest}.list"


def resolve_sources(sources: list[str], cache_dir: Path = CACHE_DIR) -> list[Path]:
    """Map configured sources to existing files on disk (never fetches).

    URL sources resolve to their cache file; a cache miss is a silent skip
    so ``apply`` stays offline-safe at boot.
    """
    paths: list[Path] = []
    for raw in sources:
        path = cache_path_for(raw, cache_dir) if is_url(raw) else Path(raw)
        if path.exists():
            paths.append(path)
    return paths


def collect_domains(
    sources: list[str], *, cache_dir: Path = CACHE_DIR
) -> list[str]:
    """Read blocklist files, return sorted unique valid domains."""
    domains: set[str] = set()
    for path in resolve_sources(sources, cache_dir):
        for line in path.read_text().splitlines():
            domain = _normalize(line)
            if domain:
                domains.add(domain)
    return sorted(domains)


def _normalize(line: str) -> str | None:
    token = line.split("#", 1)[0].strip().lower().rstrip(".")
    if not token:
        return None
    # Hosts-file form: "0.0.0.0 domain", "127.0.0.1 domain", ":: domain".
    parts = token.split()
    if len(parts) >= 2:
        try:
            ipaddress.ip_address(parts[0])
        except ValueError:
            pass
        else:
            token = parts[1].rstrip(".")
    # "0.0.0.0" is digits-only and matches the domain shape; IPs are not domains.
    try:
        ipaddress.ip_address(token)
    except ValueError:
        pass
    else:
        return None
    if not _DOMAIN_RE.match(token):
        return None
    return token


def is_domain(token: str) -> bool:
    """True if token is a syntactically valid domain name."""
    return bool(_DOMAIN_RE.match(token.strip().lower().rstrip(".")))


def render_dnsmasq(cfg: DnsConfig, domains: list[str] | None = None) -> str:
    """Render the campd dnsmasq drop-in config."""
    domains = domains if domains is not None else []
    lines = [GENERATED_HEADER]
    lines.append(f"listen-address={cfg.listen}\n")
    lines.append("bind-interfaces\n")
    lines.append(f"port={cfg.port}\n")
    lines.append("no-resolv\n")  # never read /etc/resolv.conf (it points here)
    for upstream in cfg.upstream:
        lines.append(f"server={upstream}\n")
    lines.append("stop-dns-rebind\n")
    lines.append("rebind-localhost-ok\n")
    for domain in domains:
        # Kill both A and AAAA; 0.0.0.0/:: sinkholes survive resolver caches
        # better than NXDOMAIN and are dnsmasq-documented behavior.
        lines.append(f"address=/{domain}/0.0.0.0\n")
        lines.append(f"address=/{domain}/::\n")
    return "".join(lines)


def fetch_source(
    url: str,
    dest: Path,
    *,
    opener: Callable[..., object] | None = None,
    timeout: int = FETCH_TIMEOUT_S,
    max_bytes: int = FETCH_MAX_BYTES,
) -> int:
    """Download one URL to dest atomically; returns byte size.

    A failed or oversized fetch leaves any previous dest untouched.
    """
    open_url = opener or urllib.request.urlopen
    dest.parent.mkdir(parents=True, exist_ok=True)
    with open_url(url, timeout=timeout) as resp:  # type: ignore[operator]
        fd, tmp_name = tempfile.mkstemp(dir=dest.parent, suffix=".tmp")
        tmp = Path(tmp_name)
        try:
            size = 0
            with open(fd, "wb") as fh:
                while chunk := resp.read(64 * 1024):  # type: ignore[attr-defined]
                    size += len(chunk)
                    if size > max_bytes:
                        raise OSError(f"blocklist exceeds {max_bytes} bytes")
                    fh.write(chunk)
            if size == 0:
                raise OSError("empty blocklist")
            tmp.replace(dest)
        except BaseException:
            tmp.unlink(missing_ok=True)
            raise
    return size


def fetch_blocklists(
    sources: list[str],
    cache_dir: Path = CACHE_DIR,
    *,
    opener: Callable[..., object] | None = None,
) -> list[tuple[str, str]]:
    """Fetch URL sources into cache; returns (source, status) per entry."""
    results: list[tuple[str, str]] = []
    for raw in sources:
        if not is_url(raw):
            results.append((raw, "local (not fetched)"))
            continue
        try:
            size = fetch_source(raw, cache_path_for(raw, cache_dir), opener=opener)
        except (OSError, ValueError) as exc:
            results.append((raw, f"FAILED: {exc}"))
        else:
            results.append((raw, f"cached ({size} bytes)"))
    return results


def apply(
    cfg: DnsConfig,
    *,
    write_path: Path = DNMASQ_CONF_PATH,
    cache_dir: Path = CACHE_DIR,
    reload_cmd: list[str] | None = None,
) -> None:
    """Write the drop-in config and reload dnsmasq (requires root).

    Offline-safe: URL blocklists render from cache only; missing cache
    entries are skipped, never downloaded.
    """
    import subprocess

    domains = collect_domains(cfg.blocklists, cache_dir=cache_dir)
    write_path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=write_path.parent, suffix=".tmp")
    try:
        with open(fd, "w", encoding="utf-8") as fh:
            fh.write(render_dnsmasq(cfg, domains))
        Path(tmp_name).replace(write_path)
    except BaseException:
        Path(tmp_name).unlink(missing_ok=True)
        raise
    subprocess.run(
        reload_cmd or ["systemctl", "restart", "dnsmasq"], check=False
    )
