"""Local DNS resolver with blocklists (defense-in-depth layer).

Per ADR-005 the primary control is the default-deny firewall; DNS blocking
ensures telemetry domains don't even resolve for flows the user has allowed.
Generates dnsmasq configuration — the ship-with default on Armbian.

Blocklist sources are local files of one domain per line ('#' comments and
blank lines ignored). Remote URL fetching is deliberately deferred: the
default-deny firewall must not depend on a fetch loop.
"""

from __future__ import annotations

import re
from pathlib import Path

from .config import DnsConfig

DNMASQ_CONF_PATH = Path("/etc/dnsmasq.d/campd.conf")

# Rough but safe: labels of alnum+hyphen, at least two labels, lowercase.
_DOMAIN_RE = re.compile(
    r"^(?!-)[a-z0-9-]{1,63}(?<!-)"
    r"(\.(?!-)[a-z0-9-]{1,63}(?<!-))+$"
)

GENERATED_HEADER = "# Generated by campd — do not edit (campctl dns apply)\n"


def collect_domains(blocklist_paths: list[str]) -> list[str]:
    """Read blocklist files, return sorted unique valid domains."""
    domains: set[str] = set()
    for raw in blocklist_paths:
        path = Path(raw)
        if not path.exists():
            continue
        for line in path.read_text().splitlines():
            domain = _normalize(line)
            if domain:
                domains.add(domain)
    return sorted(domains)


def _normalize(line: str) -> str | None:
    token = line.split("#", 1)[0].strip().lower().rstrip(".")
    if not token or not _DOMAIN_RE.match(token):
        return None
    return token


def is_domain(token: str) -> bool:
    """True if token is a syntactically valid domain name."""
    return bool(_DOMAIN_RE.match(token.strip().lower().rstrip(".")))


def render_dnsmasq(cfg: DnsConfig, domains: list[str] | None = None) -> str:
    """Render the campd dnsmasq drop-in config."""
    domains = domains if domains is not None else []
    lines = [GENERATED_HEADER]
    lines.append(f"listen-address={cfg.listen}\n")
    lines.append("bind-interfaces\n")
    lines.append(f"port={cfg.port}\n")
    lines.append("no-resolv\n")  # never read /etc/resolv.conf (it points here)
    for upstream in cfg.upstream:
        lines.append(f"server={upstream}\n")
    lines.append("stop-dns-rebind\n")
    lines.append("rebind-localhost-ok\n")
    for domain in domains:
        # Kill both A and AAAA; 0.0.0.0/:: sinkholes survive resolver caches
        # better than NXDOMAIN and are dnsmasq-documented behavior.
        lines.append(f"address=/{domain}/0.0.0.0\n")
        lines.append(f"address=/{domain}/::\n")
    return "".join(lines)


def apply(cfg: DnsConfig, *, write_path: Path = DNMASQ_CONF_PATH) -> None:
    """Write the drop-in config and reload dnsmasq (requires root)."""
    import subprocess

    domains = collect_domains(cfg.blocklists)
    write_path.parent.mkdir(parents=True, exist_ok=True)
    write_path.write_text(render_dnsmasq(cfg, domains))
    subprocess.run(["systemctl", "restart", "dnsmasq"], check=False)
