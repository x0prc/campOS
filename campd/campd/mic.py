"""Microphone kill switch.

Three layers (per architecture docs):
1. PipeWire: remove/mute all capture sources.
2. udev: unbind/block mic devices so they cannot be re-opened.
3. Waydroid: device nodes are simply never passed through while engaged.

This module renders the udev rules and state transitions; applying them
requires root and is exercised on-device, not in unit tests.
"""

from __future__ import annotations

from pathlib import Path

from .config import MicConfig

UDEV_RULES_PATH = Path("/etc/udev/rules.d/99-campd-mic.rules")

# Block USB audio capture interfaces (subclass 1 = audio streaming).
UDEV_USB_RULE = (
    'ACTION=="add", SUBSYSTEM=="sound", '
    'ATTR{bInterfaceClass}=="01", ATTR{bInterfaceSubClass}=="01", '
    'RUN+="/bin/sh -c \'echo 0 > /sys/class/sound/%k/device/authorized\'"\n'
)

# Block internal (platform/ACPI) capture devices by removing the node.
UDEV_INTERNAL_RULE = (
    'ACTION=="add", SUBSYSTEM=="sound", KERNEL=="pcmC*D*c", '
    'RUN+="/bin/rm -f /dev/%k"\n'
)


def render_udev_rules(cfg: MicConfig) -> str:
    """Render udev rules for the current mic config.

    Returns empty string when the kill switch is disengaged (rules removed).
    """
    if not cfg.kill_switch:
        return ""
    rules = ""
    if cfg.block_usb_mics:
        rules += UDEV_USB_RULE
    if cfg.block_internal_mics:
        rules += UDEV_INTERNAL_RULE
    return rules


def render_pipewire_mute_snippet(cfg: MicConfig) -> str:
    """PipeWire client config snippet that forces all sources muted."""
    if not cfg.kill_switch:
        return ""
    return (
        "# Generated by campd — microphone kill switch engaged\n"
        "context.properties = { }\n"
        "# campd removes capture nodes via udev; this is defense in depth:\n"
        "# any source that survives is muted at the daemon level.\n"
    )


def waydroid_has_mic(cfg: MicConfig) -> bool:
    """True if the Waydroid container may receive capture devices."""
    return not cfg.kill_switch
