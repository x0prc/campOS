from pathlib import Path

from campd.config import DnsConfig
from campd.dns import collect_domains, render_dnsmasq


def test_collect_domains_parses_and_filters(tmp_path: Path):
    bl = tmp_path / "list.txt"
    bl.write_text(
        "# tracker list\n"
        "telemetry.example.com\n"
        "\n"
        "TRACKER.EXAMPLE.ORG.\n"  # uppercase + trailing dot normalized
        "not a domain!\n"
        "localhost\n"  # single label -> rejected
        "ads.example.com # inline comment\n"
    )
    domains = collect_domains([str(bl), str(tmp_path / "missing.txt")])
    assert domains == ["ads.example.com", "telemetry.example.com",
                       "tracker.example.org"]


def test_render_base_config():
    cfg = DnsConfig(listen="127.0.0.1", port=53)
    out = render_dnsmasq(cfg, domains=[])
    assert "Generated by campd" in out
    assert "listen-address=127.0.0.1" in out
    assert "port=53" in out
    assert "bind-interfaces" in out
    assert "address=/" not in out  # no blocklist -> no sinkholes


def test_render_upstream_no_loop():
    cfg = DnsConfig(upstream=["1.1.1.1", "9.9.9.9"])
    out = render_dnsmasq(cfg, domains=[])
    assert "no-resolv\n" in out
    assert "server=1.1.1.1\n" in out
    assert "server=9.9.9.9\n" in out


def test_render_sinkholes_both_families():
    out = render_dnsmasq(DnsConfig(), domains=["ads.example.com"])
    assert "address=/ads.example.com/0.0.0.0\n" in out
    assert "address=/ads.example.com/::\n" in out


def test_collect_and_render_pipeline(tmp_path: Path):
    bl = tmp_path / "airtel-capture.txt"
    bl.write_text("metrics.airtel.example\nlogs.airtel.example\n")
    cfg = DnsConfig(blocklists=[str(bl)])
    out = render_dnsmasq(cfg, collect_domains(cfg.blocklists))
    assert out.count("address=/") == 4  # 2 domains × 2 families
